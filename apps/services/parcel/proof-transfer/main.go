// Command proof-transfer moves local delivery-proof files into private object
// storage and reconciles object keys against parcel.delivery_proofs. It is an
// operator tool, not a service. Dry-run is the default; originals are never
// deleted. Production runs require explicit approval.
package main

import (
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/signal"
	"path/filepath"
	"strings"
	"syscall"

	proofmedia "github.com/Vineth-R/swiftdrop/apps/services/parcel/internal/proof"
	sharedconfig "github.com/Vineth-R/swiftdrop/packages/go-common/config"
	"github.com/Vineth-R/swiftdrop/packages/go-common/logging"
	"github.com/Vineth-R/swiftdrop/packages/go-common/objectstore"
	"github.com/Vineth-R/swiftdrop/packages/go-common/postgres"
)

type item struct {
	ProofID  string `json:"proofId"`
	ParcelID string `json:"parcelId"`
	OldKey   string `json:"oldKey"`
	NewKey   string `json:"newKey,omitempty"`
	SHA256   string `json:"sha256,omitempty"`
	Status   string `json:"status"`
	Error    string `json:"error,omitempty"`
}

type report struct {
	Mode         string   `json:"mode"`
	SourceDir    string   `json:"sourceDir,omitempty"`
	Total        int      `json:"total"`
	Transferred  int      `json:"transferred"`
	Skipped      int      `json:"skipped"`
	Missing      int      `json:"missing"`
	Failed       int      `json:"failed"`
	SizeMismatch int      `json:"sizeMismatch"`
	MIMEMismatch int      `json:"mimeMismatch"`
	Orphans      []string `json:"orphans,omitempty"`
	Items        []item   `json:"items"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "proof-transfer:", err)
		os.Exit(1)
	}
}

func run() error {
	apply := flag.Bool("apply", false, "upload files and update photo_path; default is a dry run")
	reconcile := flag.Bool("reconcile", false, "compare database keys with object storage instead of transferring")
	reportPath := flag.String("report", "", "write the full JSON report to this path")
	flag.Parse()

	if *apply && *reconcile {
		return errors.New("--apply and --reconcile cannot be combined")
	}

	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()

	databaseURL := strings.TrimSpace(os.Getenv("DATABASE_URL_DIRECT"))
	if databaseURL == "" {
		databaseURL = strings.TrimSpace(os.Getenv("DATABASE_URL"))
	}
	databaseConfig, err := postgres.LoadConfigFromURL(databaseURL)
	if err != nil {
		return fmt.Errorf("configure database: %w", err)
	}
	if !databaseConfig.Configured() {
		return errors.New("DATABASE_URL_DIRECT or DATABASE_URL is required")
	}
	database, err := postgres.Open(ctx, databaseConfig)
	if err != nil {
		return fmt.Errorf("connect database: %w", err)
	}
	defer database.Close()

	storageConfig, err := objectstore.LoadConfig(sharedconfig.Load())
	if err != nil {
		return fmt.Errorf("configure object storage: %w", err)
	}
	storage, err := objectstore.New(ctx, storageConfig)
	if err != nil {
		return fmt.Errorf("configure object storage: %w", err)
	}
	defer storage.Close()

	if *reconcile {
		result, reconcileErr := reconcileKeys(ctx, database, storage)
		if err := writeReport(*reportPath, result); err != nil {
			return err
		}
		return reconcileErr
	}

	sourceDir := strings.TrimSpace(os.Getenv("PROOF_STORAGE_DIR"))
	if sourceDir == "" {
		return errors.New("PROOF_STORAGE_DIR is required for transfer")
	}
	result, err := transferProofs(ctx, database, storage, sourceDir, *apply)
	if err != nil {
		return err
	}
	if err := writeReport(*reportPath, result); err != nil {
		return err
	}
	if result.Failed > 0 {
		return fmt.Errorf("%d proof(s) failed; see the report", result.Failed)
	}
	return nil
}

func transferProofs(ctx context.Context, database *postgres.Pool, storage objectstore.Store, sourceDir string, apply bool) (report, error) {
	result := report{Mode: "transfer", SourceDir: sourceDir, Items: []item{}}
	if !apply {
		result.Mode = "dry-run"
	}
	rows, err := database.Query(ctx, `SELECT id, parcel_id, photo_path, photo_mime_type
		FROM parcel.delivery_proofs WHERE photo_path IS NOT NULL ORDER BY created_at, id`)
	if err != nil {
		return report{}, fmt.Errorf("read delivery proofs: %w", err)
	}
	defer rows.Close()

	for rows.Next() {
		var id, parcelID, oldKey string
		var mimeType *string
		if err := rows.Scan(&id, &parcelID, &oldKey, &mimeType); err != nil {
			return report{}, fmt.Errorf("scan delivery proof: %w", err)
		}
		result.Total++
		entry := item{ProofID: id, ParcelID: parcelID, OldKey: oldKey}

		if mimeType == nil || (*mimeType != "image/jpeg" && *mimeType != "image/png") {
			entry.Status, entry.Error = "failed", "unsupported or missing photo_mime_type"
			result.Failed++
			result.Items = append(result.Items, entry)
			continue
		}

		// A key already generated by the Parcel service is idempotent.
		if objectstore.ValidKey(oldKey) && strings.HasPrefix(oldKey, parcelID+"/") {
			info, statErr := storage.Stat(ctx, oldKey)
			switch {
			case statErr == nil && info.Size > 0:
				entry.Status = "skipped"
				result.Skipped++
			case errors.Is(statErr, objectstore.ErrNotFound):
				entry.Status, entry.Error = "missing", "object referenced by the database is absent"
				result.Missing++
			default:
				entry.Status, entry.Error = "failed", "could not verify existing object"
				result.Failed++
			}
			result.Items = append(result.Items, entry)
			continue
		}

		newKey, keyErr := proofmedia.NewKey(parcelID, id, *mimeType)
		if keyErr != nil {
			entry.Status, entry.Error = "failed", "stored proof ID or MIME type is invalid"
			result.Failed++
			result.Items = append(result.Items, entry)
			continue
		}
		entry.NewKey = newKey

		data, readErr := readSource(sourceDir, oldKey)
		if readErr != nil {
			entry.Status, entry.Error = "missing", "local proof file is missing or unreadable"
			result.Missing++
			result.Items = append(result.Items, entry)
			continue
		}
		metadata, validateErr := proofmedia.ValidatePhoto(data, *mimeType)
		if validateErr != nil {
			entry.Status, entry.Error = "failed", "local proof file failed content validation"
			result.Failed++
			result.Items = append(result.Items, entry)
			continue
		}

		sourceSum := sha256.Sum256(data)
		entry.SHA256 = hex.EncodeToString(sourceSum[:])
		if !apply {
			entry.Status = "planned"
			result.Items = append(result.Items, entry)
			continue
		}

		if putErr := storage.Put(ctx, newKey, data, metadata.MIMEType); putErr != nil {
			entry.Status, entry.Error = "failed", "upload failed"
			result.Failed++
			result.Items = append(result.Items, entry)
			continue
		}
		info, statErr := storage.Stat(ctx, newKey)
		if statErr != nil || info.Size != int64(metadata.SizeBytes) {
			entry.Status, entry.Error = "failed", "uploaded object size verification failed"
			result.Failed++
			result.Items = append(result.Items, entry)
			continue
		}
		if info.ContentType != "" && info.ContentType != metadata.MIMEType {
			entry.Status, entry.Error = "failed", "uploaded object content type does not match the source"
			result.Failed++
			result.Items = append(result.Items, entry)
			continue
		}
		uploadedSum, checksumErr := objectChecksum(ctx, storage, newKey)
		if checksumErr != nil || !bytes.Equal(uploadedSum, sourceSum[:]) {
			entry.Status, entry.Error = "failed", "uploaded object checksum does not match the source"
			result.Failed++
			result.Items = append(result.Items, entry)
			continue
		}
		tag, updateErr := database.Exec(ctx, `UPDATE parcel.delivery_proofs
			SET photo_path=$2 WHERE id=$1 AND photo_path=$3`, id, newKey, oldKey)
		if updateErr != nil || tag.RowsAffected() != 1 {
			entry.Status, entry.Error = "failed", "database update did not apply"
			result.Failed++
			result.Items = append(result.Items, entry)
			continue
		}
		entry.Status = "transferred"
		result.Transferred++
		result.Items = append(result.Items, entry)
	}
	if err := rows.Err(); err != nil {
		return report{}, fmt.Errorf("iterate delivery proofs: %w", err)
	}
	return result, nil
}

func reconcileKeys(ctx context.Context, database *postgres.Pool, storage objectstore.Store) (report, error) {
	result := report{Mode: "reconcile", Items: []item{}}
	rows, err := database.Query(ctx, `SELECT id, parcel_id, photo_path, photo_mime_type, photo_size_bytes
		FROM parcel.delivery_proofs WHERE photo_path IS NOT NULL ORDER BY created_at, id`)
	if err != nil {
		return report{}, fmt.Errorf("read delivery proofs: %w", err)
	}
	defer rows.Close()

	stored, err := storage.List(ctx, "")
	if err != nil {
		return report{}, fmt.Errorf("list stored objects: %w", err)
	}
	objectKeys := make(map[string]struct{}, len(stored))
	for _, key := range stored {
		if objectstore.ValidKey(key) {
			objectKeys[key] = struct{}{}
		}
	}
	databaseKeys := map[string]struct{}{}
	for rows.Next() {
		var id, parcelID, key string
		var mimeType *string
		var sizeBytes *int
		if err := rows.Scan(&id, &parcelID, &key, &mimeType, &sizeBytes); err != nil {
			return report{}, fmt.Errorf("scan delivery proof: %w", err)
		}
		result.Total++
		databaseKeys[key] = struct{}{}
		if _, ok := objectKeys[key]; !ok {
			result.Missing++
			result.Items = append(result.Items, item{ProofID: id, ParcelID: parcelID, OldKey: key, Status: "missing"})
			continue
		}
		info, statErr := storage.Stat(ctx, key)
		if statErr != nil {
			result.Missing++
			result.Items = append(result.Items, item{ProofID: id, ParcelID: parcelID, OldKey: key, Status: "missing", Error: "object could not be inspected"})
			continue
		}
		if sizeBytes != nil && info.Size != int64(*sizeBytes) {
			result.SizeMismatch++
			result.Items = append(result.Items, item{ProofID: id, ParcelID: parcelID, OldKey: key, Status: "size_mismatch"})
			continue
		}
		if mimeType != nil && info.ContentType != "" && info.ContentType != *mimeType {
			result.MIMEMismatch++
			result.Items = append(result.Items, item{ProofID: id, ParcelID: parcelID, OldKey: key, Status: "mime_mismatch"})
		}
	}
	if err := rows.Err(); err != nil {
		return report{}, fmt.Errorf("iterate delivery proofs: %w", err)
	}
	for key := range objectKeys {
		if _, ok := databaseKeys[key]; !ok {
			result.Orphans = append(result.Orphans, key)
		}
	}
	if result.Missing > 0 || result.Failed > 0 || result.SizeMismatch > 0 || result.MIMEMismatch > 0 || len(result.Orphans) > 0 {
		return result, fmt.Errorf("reconciliation found missing, mismatched or orphaned objects")
	}
	return result, nil
}

func objectChecksum(ctx context.Context, storage objectstore.Store, key string) ([]byte, error) {
	object, err := storage.Open(ctx, key)
	if err != nil {
		return nil, err
	}
	defer func() { _ = object.Body.Close() }()
	data, err := io.ReadAll(object.Body)
	if err != nil {
		return nil, err
	}
	sum := sha256.Sum256(data)
	return sum[:], nil
}

func readSource(directory, key string) ([]byte, error) {
	root, err := filepath.Abs(directory)
	if err != nil {
		return nil, err
	}
	candidate := filepath.Join(root, filepath.FromSlash(key))
	clean := filepath.Clean(candidate)
	if clean != root && !strings.HasPrefix(clean, root+string(os.PathSeparator)) {
		return nil, errors.New("proof path escapes the source directory")
	}
	return os.ReadFile(clean)
}

func writeReport(path string, result report) error {
	encoded, err := json.MarshalIndent(result, "", "  ")
	if err != nil {
		return err
	}
	if path != "" {
		if err := os.WriteFile(path, append(encoded, '\n'), 0o600); err != nil {
			return fmt.Errorf("write report: %w", err)
		}
	}
	logging.NewBootstrap("proof-transfer").Info("proof transfer summary",
		"mode", result.Mode,
		"total", result.Total,
		"transferred", result.Transferred,
		"skipped", result.Skipped,
		"missing", result.Missing,
		"failed", result.Failed,
		"sizeMismatch", result.SizeMismatch,
		"mimeMismatch", result.MIMEMismatch,
		"orphans", len(result.Orphans),
	)
	if path == "" {
		fmt.Println(string(encoded))
	} else {
		fmt.Println(path)
	}
	return nil
}
