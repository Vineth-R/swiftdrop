package repository

import (
	"context"
	"fmt"
	"time"
)

// RecordAttemptParams is one webhook delivery attempt reported by the webhook
// worker (API v1.1 section 13).
type RecordAttemptParams struct {
	ID             string // new row id, generated by the caller
	MerchantID     string
	EventID        string
	ParcelID       string
	TrackingNumber string
	AttemptNumber  int
	HTTPStatus     *int // nil when no response arrived (timeout, connection error)
	Success        bool
	ErrorMessage   *string // safe text only, never a payload or a secret
	NextRetryAt    *time.Time
	DeadLettered   bool
	DurationMS     *int
}

// RecordDeliveryAttempt stores one attempt for the merchant's webhook.
//
// It is idempotent: the table has UNIQUE (webhook_id, event_id,
// attempt_number), so a worker that retries the same report, or a message that
// is redelivered, cannot record the same attempt twice. The boolean is true
// when a new row was written and false when the attempt was already recorded.
//
// It returns ErrWebhookNotConfigured when the merchant has no webhook, because
// an attempt always belongs to a webhook row.
func (r *Repository) RecordDeliveryAttempt(ctx context.Context, p RecordAttemptParams) (bool, error) {
	webhook, err := r.WebhookByMerchant(ctx, p.MerchantID)
	if err != nil {
		return false, err
	}

	tag, err := r.db.Exec(ctx, `
INSERT INTO `+attemptsTable+`
    (id, event_id, webhook_id, merchant_id, parcel_id, tracking_number, attempt_number,
     http_status, success, error_message, next_retry_at, dead_lettered, duration_ms, created_at)
VALUES ($1::uuid, $2::uuid, $3::uuid, $4::uuid, $5::uuid, $6, $7, $8, $9, $10, $11, $12, $13, now())
ON CONFLICT ON CONSTRAINT webhook_attempt_uq DO NOTHING`,
		p.ID, p.EventID, webhook.ID, p.MerchantID, p.ParcelID, p.TrackingNumber, p.AttemptNumber,
		p.HTTPStatus, p.Success, p.ErrorMessage, p.NextRetryAt, p.DeadLettered, p.DurationMS)
	if err != nil {
		return false, fmt.Errorf("record delivery attempt: %w", err)
	}
	return tag.RowsAffected() == 1, nil
}
